// Generates Code Connect mappings for standalone SVG icons on the Figma Icons page.
// Usage: node --env-file=.env scripts/generate-figma-icon-connect.mjs
import fs from "node:fs";
import path from "node:path";

const FILE_KEY = "3ZH2uUGxYtIItgBpwjz4NC";
const ICONS_PAGE_ID = "6594:47638";
const OUTPUT = path.resolve(
  "src/components/mui/data-display/IconCatalog.figma.tsx",
);
const EXCLUDED_NODE_IDS = new Set([
  // Kept in its existing dedicated mapping file.
  "11613:424603", // UnfoldMoreOutlined
]);

const token = process.env.FIGMA_ACCESS_TOKEN;
if (!token) {
  console.error("FIGMA_ACCESS_TOKEN not set");
  process.exit(1);
}

const response = await fetch(
  `https://api.figma.com/v1/files/${FILE_KEY}/nodes?ids=${ICONS_PAGE_ID}`,
  { headers: { "X-Figma-Token": token } },
);
if (!response.ok) {
  console.error(`Figma API ${response.status}: ${await response.text()}`);
  process.exit(1);
}

const page = (await response.json()).nodes?.[ICONS_PAGE_ID]?.document;
if (!page) {
  console.error(`Figma page ${ICONS_PAGE_ID} not found`);
  process.exit(1);
}

const figmaIcons = [];
function collect(node, parentType = null) {
  if (
    node.type === "COMPONENT" &&
    parentType !== "COMPONENT_SET" &&
    node.name !== "_hidden" &&
    !EXCLUDED_NODE_IDS.has(node.id)
  ) {
    figmaIcons.push({ id: node.id, figmaName: node.name });
  }
  for (const child of node.children ?? []) collect(child, node.type);
}
collect(page);

const muiModules = new Set(
  fs
    .readdirSync(path.resolve("node_modules/@mui/icons-material"))
    .filter((name) => name.endsWith(".js"))
    .map((name) => name.slice(0, -3)),
);

// The Figma library uses "Filled" as a style suffix meaning MUI's default,
// unsuffixed icon, so the stripped name is tried first. A handful of MUI modules
// genuinely end in "Filled" (HomeFilled, AccessTimeFilled) and are different
// glyphs from the Figma icons of the same name, so preferring the literal name
// would silently map to the wrong artwork.
function moduleCandidates(figmaName) {
  const names = [];
  if (figmaName.endsWith("Filled")) {
    const withoutFilled = figmaName.slice(0, -"Filled".length);
    names.push(withoutFilled, withoutFilled.replace("Openin", "OpenIn"));
  }
  names.push(figmaName, figmaName.replace("Openin", "OpenIn"));
  return [...new Set(names)];
}

const mappings = figmaIcons
  .map(({ id, figmaName }) => ({
    id,
    figmaName,
    muiName: moduleCandidates(figmaName).find((name) => muiModules.has(name)),
  }))
  .sort((a, b) => a.figmaName.localeCompare(b.figmaName));

const unresolved = mappings.filter(({ muiName }) => !muiName);
if (unresolved.length) {
  console.error("No @mui/icons-material match for:");
  for (const icon of unresolved) console.error(`- ${icon.id} ${icon.figmaName}`);
  process.exit(1);
}

const imports = mappings
  .map(
    ({ figmaName, muiName }) =>
      `import ${figmaName}Icon from "@mui/icons-material/${muiName}";`,
  )
  .join("\n");

const connects = mappings
  .map(
    ({ id, figmaName }) => `figma.connect(
  ${figmaName}Icon,
  "https://www.figma.com/design/${FILE_KEY}/UAX-DS---Core-Component-Library--Styles--and-Variables?node-id=${id.replace(":", "%3A")}",
  {
    example: () => <${figmaName}Icon />,
  },
);`,
  )
  .join("\n\n");

const output = `// GENERATED by scripts/generate-figma-icon-connect.mjs — do not edit by hand.
// Figma source component names intentionally remain visible as local aliases.
import React from "react";
import figma from "@figma/code-connect";
${imports}

${connects}
`;

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, output);
console.log(
  `Generated ${mappings.length} icon mappings at ${path.relative(process.cwd(), OUTPUT)}`,
);
